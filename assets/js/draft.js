// Початкові дані для прикладів
const numbers = [10, 5, 20, 15, 30];
const users = [
  { id: 1, name: "Іван", age: 25 },
  { id: 2, name: "Марія", age: 17 },
  { id: 3, name: "Петро", age: 30 },
];

/* ==========================================================================
   1. forEach — Простий обхід (коли треба зробити дію для кожного елемента)
   --------------------------------------------------------------------------
   • Повертає: undefined
   • Змінює оригінал: Ні
   • Use case: Консоль-лог, відправка запитів, запис у зовнішні змінні.
   ========================================================================== */
numbers.forEach((num, index) => {
  console.log(`Індекс ${index}: ${num}`);
});

/* ==========================================================================
   2. map — Трансформація елементів
   --------------------------------------------------------------------------
   • Повертає: Новий масив ТАКОЇ Ж довжини з модифікованими елементами
   • Змінює оригінал: Ні
   • Use case: Витягти певні поля, змінити формат даних, розрахувати значення.
   ========================================================================== */
const doubled = numbers.map((num) => num * 2);
// [20, 10, 40, 30, 60]

const namesOnly = users.map((user) => user.name);
// ["Іван", "Марія", "Петро"]

/* ==========================================================================
   3. filter — Відбір елементів за умовою
   --------------------------------------------------------------------------
   • Повертає: Новий масив (тільки ті елементи, де колбек повернув true)
   • Змінює оригінал: Ні
   • Use case: Пошук списку, фільтрація товарів за ціною/категорією.
   ========================================================================== */
const adults = users.filter((user) => user.age >= 18);
// [{ id: 1, name: "Іван", ... }, { id: 3, name: "Петро", ... }]

const greaterThan12 = numbers.filter((num) => num > 12);
// [20, 15, 30]

/* ==========================================================================
   4. find & findIndex — Пошук ОДНОГО елемента або його індексу
   --------------------------------------------------------------------------
   • Повертає: Перший знайдений елемент (або undefined) / індекс (або -1)
   • Змінює оригінал: Ні
   • Use case: Пошук об'єкта за унікальним id або назвою.
   ========================================================================== */
const maria = users.find((user) => user.name === "Марія");
// { id: 2, name: "Марія", age: 17 }

const mariaIndex = users.findIndex((user) => user.name === "Марія");
// 1

/* ==========================================================================
   5. some & every — Перевірка на відповідність умові (повертають boolean)
   --------------------------------------------------------------------------
   • Повертає: true або false
   • Змінює оригінал: Ні
   • Use case: Валідація (чи є хоч один неповнолітній / чи всі погодилися з правилами).
   ========================================================================== */
// some: повертає true, якщо ХОЧ ОДИН елемент відповідає умові
const hasMinors = users.some((user) => user.age < 18); // true

// every: повертає true, тільки якщо ВСІ елементи відповідають умові
const allAdults = users.every((user) => user.age >= 18); // false

/* ==========================================================================
   6. reduce — Агрегація (зведення масиву до одного значення або об'єкта)
   --------------------------------------------------------------------------
   • Повертає: Накопичений результат (acc)
   • Змінює оригінал: Ні
   • Use case: Сума цін, підрахунок кількості, групування елементів.
   ========================================================================== */
// Сума всіх чисел (0 — це початкове значення акумулятора acc):
const totalSum = numbers.reduce((acc, current) => acc + current, 0);
// 80

// Групування за віковим статусом в один об'єкт:
const grouped = users.reduce(
  (acc, user) => {
    const key = user.age >= 18 ? "adults" : "minors";
    acc[key].push(user.name);
    return acc;
  },
  { adults: [], minors: [] },
);
// { adults: ["Іван", "Петро"], minors: ["Марія"] }

/* ==========================================================================
   7. flatMap — Трансформація + «розплющення» (flattening)
   --------------------------------------------------------------------------
   • Повертає: Новий плоский масив
   • Змінює оригінал: Ні
   • Use case: Розбиття слів, об'єднання масивів з декількох об'єктів.
   ========================================================================== */
const phrases = ["Привіт світ", "JS це круто"];
const words = phrases.flatMap((phrase) => phrase.split(" "));
// ["Привіт", "світ", "JS", "це", "круто"]

/* ==========================================================================
   8. sort & toSorted — Сортування
   --------------------------------------------------------------------------
   • sort(): МУТУЄ (змінює) оригінальний масив!
   • toSorted(): Повертає новий відсортований масив (ES2023).
   ========================================================================== */
// Звичайний sort (робимо копію [...numbers], щоб не зламати оригінал):
const sortedAsc = [...numbers].sort((a, b) => a - b); // За зростанням: [5, 10, 15, 20, 30]
const sortedDesc = [...numbers].sort((a, b) => b - a); // За спаданням: [30, 20, 15, 10, 5]

// Сортування об'єктів за віком:
const sortedByAge = [...users].sort((a, b) => a.age - b.age);

